package codegen

import (
	"bytes"
	"fmt"
	"go/format"
	"io"
	"strconv"
	"strings"

	"github.com/adhocteam/pushup/internal/ast"
	"github.com/adhocteam/pushup/internal/source"
	"github.com/adhocteam/pushup/internal/up"
	"github.com/adhocteam/pushup/internal/version"
)

type Generator interface {
	Generate(*up.CompileUnit) ([]byte, error)
}

type generateFunc func(*up.CompileUnit) ([]byte, error)

func (f generateFunc) Generate(unit *up.CompileUnit) ([]byte, error) {
	return f(unit)
}

type generator struct {
	unit    *up.CompileUnit
	imports map[string]string
	content sections
}

type sections struct {
	comments bytes.Buffer
	imports  bytes.Buffer
	code     bytes.Buffer
}

func (s *sections) reset() {
	(&s.comments).Reset()
	(&s.imports).Reset()
	(&s.code).Reset()
}

func New() *generator {
	return &generator{
		imports: make(map[string]string),
	}
}

const (
	methodReceiverName = "up"
	ioWriterVar        = "__pushup_b"
	pushupApi          = "github.com/adhocteam/pushup"
	pushupModulePath   = "github.com/adhocteam/pushup"
)

func (g *generator) Generate(unit *up.CompileUnit) ([]byte, error) {
	g.unit = unit
	g.content.reset()

	g.addComment("Code generated by Pushup; DO NOT EDIT")
	g.addComment("Version: " + version.Version())

	g.generateResponder(unit.TypeName, unit.Handler, g.generate)

	// Register route
	g.println("")
	g.println("func init() {")
	g.addImport(pushupModulePath+"/route", "")
	g.printf("route.Register(\"%s\", new(%s))\n", unit.Route, unit.TypeName)
	g.println("}")
	g.println("")

	for _, partial := range g.unit.Partials {
		g.generateResponder(partial.TypeName, unit.Handler, func() {
			// FIXME(paulsmith): need to generate code for everything but emitting
			// top-level page values to the output
			g.genNodePartial(ast.NodeList(g.unit.Nodes), partial)
		})
	}

	raw, err := g.bytes()
	if err != nil {
		return nil, fmt.Errorf("getting generated code bytes: %w", err)
	}

	code, err := format.Source(raw)
	if err != nil {
		return nil, fmt.Errorf("formatting generated Go code: %w", err)
	}

	return code, nil
}

func (g *generator) generateResponder(typename string, handler *ast.NodeGoCode, codegenFn func()) {
	g.printf("type %s struct {", typename)
	// TODO: fields?
	g.println("}")

	g.addImport("net/http", "")
	g.printf("func (%s *%s) Respond(w http.ResponseWriter, req *http.Request) error {\n", methodReceiverName, typename)

	// NOTE(paulsmith): we might want to encapsulate this in its own
	// function/method, but would have to figure out the interplay between
	// user code and control flow, i.e., return an error if the handler
	// wants to skip rendering, redirect, etc.
	if handler != nil {
		srcLineNo := g.lineNo(handler.Pos())
		lines := strings.Split(handler.Code, "\n")
		for _, line := range lines {
			g.emitLineDirective(srcLineNo)
			g.println(line)
			srcLineNo++
		}
	}

	// Make a new scope for the user's code block and HTML. This will help (but not fully prevent)
	// name collisions with the surrounding code.
	g.println("// Begin user Go code and HTML")
	g.println("{")

	g.addImport("bytes", "")
	g.printf("%s := new(bytes.Buffer)\n", ioWriterVar)
	codegenFn()
	g.println("io.Copy(w, __pushup_b)")

	g.println("}")
	g.println("// End user Go code and HTML")

	g.println("return nil")
	g.println("}") // end Respond() method
}

func (g *generator) generate() {
	g.genNode(ast.NodeList(g.unit.Nodes))
}

func (g *generator) nodeLineNo(e ast.Node) {
	g.emitLineDirective(g.lineNo(e.Pos()))
}

func (g *generator) genNode(e ast.Node) {
	var f ast.Inspector
	f = func(e ast.Node) bool {
		switch e := e.(type) {
		case *ast.NodeLiteral:
			g.addImport("io", "")
			g.nodeLineNo(e)
			g.printf("io.WriteString(%s, %s)\n", ioWriterVar, strconv.Quote(e.Text))
		case *ast.NodeElement:
			g.genElement(e, f)
			return false
		case *ast.NodeGoStrExpr:
			g.nodeLineNo(e)
			g.addImport(pushupApi, "api")
			g.printf("api.PrintEscaped(%s, %s)\n", ioWriterVar, e.Expr)
		case *ast.NodeGoCode:
			if e.Context != ast.InlineGoCode {
				panic("internal error: expected inlineGoCode")
			}
			srcLineNo := g.lineNo(e.Pos())
			lines := strings.Split(e.Code, "\n")
			for _, line := range lines {
				g.emitLineDirective(srcLineNo)
				g.println(line)
				srcLineNo++
			}
		case *ast.NodeIf:
			g.printf("if %s {\n", e.Cond.Expr)
			f(e.Then)
			if e.Alt == nil {
				g.println("}")
			} else {
				g.println("} else {")
				f(e.Alt)
				g.println("}")
			}
			return false
		case ast.NodeList:
			for _, x := range e {
				f(x)
			}
			return false
		case *ast.NodeFor:
			g.printf("for %s {\n", e.Clause.Code)
			f(e.Block)
			g.println("}")
			return false
		case *ast.NodeBlock:
			f(ast.NodeList(e.Nodes))
			return false
		case *ast.NodePartial:
			f(e.Block)
			return false
		case *ast.NodeImport:
			// nothing to do
		}
		return true
	}

	ast.Inspect(e, f)
}

// NOTE(paulsmith): per DOM spec, "In tree order is preorder, depth-first traversal of a tree."

func (g *generator) genNodePartial(n ast.Node, p *up.Partial) {
	var f ast.Inspector
	var state int
	const (
		stateStart int = iota
		stateInPartialScope
	)
	state = stateStart
	f = func(n ast.Node) bool {
		if n != nil {
			switch n := n.(type) {
			case *ast.NodeLiteral:
				if state == stateInPartialScope {
					g.addImport("io", "")
					g.nodeLineNo(n)
					g.printf("io.WriteString(%s, %s)\n", ioWriterVar, strconv.Quote(n.Text))
				}
			case *ast.NodeElement:
				if state == stateInPartialScope {
					g.addImport("io", "")
					g.nodeLineNo(n)
					f(ast.NodeList(n.StartTagNodes))
				}
				f(ast.NodeList(n.Children))
				if state == stateInPartialScope {
					g.printf("io.WriteString(%s, %s)\n", ioWriterVar, strconv.Quote(n.Tag.End()))
				}
				return false
			case *ast.NodePartial:
				if n == p.Node {
					state = stateInPartialScope
				}
				f(n.Block)
				state = stateStart
				return false
			case *ast.NodeGoStrExpr:
				if state == stateInPartialScope {
					g.nodeLineNo(n)
					g.addImport(pushupApi, "api")
					g.printf("api.PrintEscaped(%s, %s)\n", ioWriterVar, n.Expr)
				}
			case *ast.NodeFor:
				if state == stateInPartialScope {
					g.printf("for %s {\n", n.Clause.Code)
					f(n.Block)
					g.println("}")
				}
				return false
			case *ast.NodeIf:
				g.printf("if %s {\n", n.Cond.Expr)
				f(n.Then)
				if n.Alt == nil {
					g.println("}")
				} else {
					g.println("} else {")
					f(n.Alt)
					g.println("}")
				}
				return false
			case *ast.NodeGoCode:
				if n.Context != ast.InlineGoCode {
					panic("internal error: expected inlineGoCode")
				}
				srcLineNo := g.lineNo(n.Pos())
				lines := strings.Split(n.Code, "\n")
				for _, line := range lines {
					g.emitLineDirective(srcLineNo)
					g.println(line)
					srcLineNo++
				}
			case ast.NodeList:
				for _, x := range n {
					f(x)
				}
			case *ast.NodeBlock:
				for _, x := range n.Nodes {
					f(x)
				}
			default:
				panic(fmt.Sprintf("internal error: unhandled node type %T", n))
			}
		}
		return false
	}
	ast.Inspect(n, f)
}

func (g *generator) genElement(e *ast.NodeElement, f ast.Inspector) {
	g.addImport("io", "")
	g.nodeLineNo(e)
	f(ast.NodeList(e.StartTagNodes))
	f(ast.NodeList(e.Children))
	g.printf("io.WriteString(%s, %s)\n", ioWriterVar, strconv.Quote(e.Tag.End()))
}

func (g *generator) addComment(comment string) {
	fmt.Fprintln(&g.content.comments, "//", comment)
}

func (g *generator) addImport(path, pkgName string) {
	g.imports[path] = pkgName
}

func (g *generator) println(code string) {
	fmt.Fprintln(&g.content.code, code)
}

func (g *generator) printf(format string, a ...any) {
	fmt.Fprintf(&g.content.code, format, a...)
}

func (g *generator) lineNo(s source.Span) int {
	return lineCount(g.unit.File.Content[:s.Start+1])
}

func (g *generator) emitLineDirective(n int) {
	fmt.Fprintf(&g.content.code, "//line %s:%d\n", g.unit.File.Path, n)
}

func (g *generator) bytes() ([]byte, error) {
	pkgDecl := strings.NewReader("package " + g.unit.Package + "\n")

	if len(g.imports) > 0 {
		fmt.Fprintln(&g.content.imports, "import (")
		for path, pkgName := range g.imports {
			if pkgName == "" {
				fmt.Fprintf(&g.content.imports, "\t%q\n", path)
			} else {
				fmt.Fprintf(&g.content.imports, "\t%s %q\n", pkgName, path)
			}
		}
		fmt.Fprintln(&g.content.imports, ")")
	}

	bufs := []io.Reader{
		&g.content.comments,
		pkgDecl,
		&g.content.imports,
		&g.content.code,
	}
	return io.ReadAll(io.MultiReader(bufs...))
}

var nl = []byte{'\n'}

func lineCount(s []byte) int {
	return bytes.Count(s, nl) + 1
}
